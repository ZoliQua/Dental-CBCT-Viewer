#!/usr/bin/env node
/**
 * Static build of the DenCT app for https://dulzoltan.hu/denct — a regular
 * web host serving the app from the /denct/ sub-path (not the Vercel demo).
 *
 *   npm run build:dulzoltan   →   dist-dulzoltan/   (gitignored)
 *
 * Upload the CONTENTS of dist-dulzoltan/ into the site's /denct directory.
 * Besides the Vite build (base /denct/) it writes:
 *  - .htaccess   the headers the viewer needs (COOP/COEP for SharedArrayBuffer
 *                in the DICOM decode workers), the same CSP as the Vercel demo,
 *                and the application/wasm MIME type. Apache / LiteSpeed only —
 *                on nginx set the same headers in the server config.
 *  - version.txt which release + commit is deployed.
 * Runs as part of every release (see CONTRIBUTING → Releasing).
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'dist-dulzoltan');
const BASE = '/denct/';
const run = (cmd) => execSync(cmd, { cwd: ROOT, stdio: 'inherit' });

run('npx tsc -b');
run(`npx vite build --base=${BASE} --outDir ${OUT} --emptyOutDir`);

const htaccess = `# DenCT — https://dulzoltan.hu${BASE}
# Generated by scripts/build-dulzoltan.cjs — do not edit by hand.

DirectoryIndex index.html

# WebAssembly must be served as application/wasm (streaming compilation).
AddType application/wasm .wasm

<IfModule mod_headers.c>
  # Cross-origin isolation: required for SharedArrayBuffer in the DICOM decode
  # workers — without these two headers image decoding does not run.
  Header always set Cross-Origin-Opener-Policy "same-origin"
  Header always set Cross-Origin-Embedder-Policy "require-corp"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "no-referrer"
  Header always set Content-Security-Policy "default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; worker-src 'self' blob:; img-src 'self' blob: data:; style-src 'self' 'unsafe-inline'; connect-src 'self' blob: data:; font-src 'self' data:; object-src 'none'; base-uri 'self'"

  # Hashed build assets never change → cache for a year; index.html always fresh.
  <FilesMatch "\\.(js|css|wasm|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "^index\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

# The sample volume is already gzip-compressed — don't compress it again.
<IfModule mod_deflate.c>
  SetEnvIfNoCase Request_URI "\\.bin$" no-gzip
</IfModule>
`;
fs.writeFileSync(path.join(OUT, '.htaccess'), htaccess);

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
let commit = 'unknown';
try { commit = execSync('git rev-parse --short HEAD', { cwd: ROOT }).toString().trim(); } catch { /* not a git checkout */ }
fs.writeFileSync(path.join(OUT, 'version.txt'),
  `DenCT ${pkg.version}\ncommit ${commit}\nbuilt ${new Date().toISOString()}\nbase ${BASE}\n`);

console.log(`\n✓ dist-dulzoltan/ ready — DenCT ${pkg.version} (${commit}) for https://dulzoltan.hu${BASE}`);
console.log('  Upload the folder CONTENTS (including the hidden .htaccess) into /denct on the web host.');
